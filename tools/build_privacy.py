"""Regenerates the policy on privacy/index.html from the app repo's Markdown,
so the site and the app's policy never drift apart. Only the part between the
POLICY markers is replaced; the page's head, header and footer stay as written.

    python3 tools/build_privacy.py
"""
import html
import re
from pathlib import Path

SOURCE = Path.home() / "AndroidStudioProjects/golftrace/docs/legal/privacy.md"
PAGE = Path(__file__).resolve().parent.parent / "privacy/index.html"
BEGIN = "<!-- POLICY:BEGIN generated by tools/build_privacy.py from golftrace/docs/legal/privacy.md -->"
END = "<!-- POLICY:END -->"
EMAIL = "support@kikigadgetsltd.com"


def inline(text: str) -> str:
    text = html.escape(text, quote=False)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    return text.replace(EMAIL, f'<a href="mailto:{EMAIL}">{EMAIL}</a>')


def to_html(markdown: str) -> str:
    """The Markdown subset the policy uses: # and ## headings, **bold**, "- "
    lists, one pipe table, and paragraphs whose lines break with <br>."""
    lines = markdown.splitlines()
    out, para, i = [], [], 0

    def flush():
        if para:
            out.append("  <p>" + "<br>\n  ".join(inline(x) for x in para) + "</p>")
            para.clear()

    while i < len(lines):
        line = lines[i]
        if line.startswith("# "):
            flush()
            out.append(f"  <h1>{inline(line[2:])}</h1>")
        elif line.startswith("## "):
            flush()
            out.append(f"\n  <h2>{inline(line[3:])}</h2>")
        elif line.startswith("- "):
            flush()
            items = []
            while i < len(lines) and lines[i].startswith("- "):
                items.append(f"    <li>{inline(lines[i][2:])}</li>")
                i += 1
            out.append("  <ul>\n" + "\n".join(items) + "\n  </ul>")
            continue
        elif line.startswith("|"):
            flush()
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                rows.append([c.strip() for c in lines[i].strip().strip("|").split("|")])
                i += 1
            head, body = rows[0], rows[2:]  # rows[1] is the |---| separator
            table = ["  <table>", "    <thead><tr>" + "".join(f"<th>{inline(c)}</th>" for c in head) + "</tr></thead>",
                     "    <tbody>"]
            table += ["      <tr>" + "".join(f"<td>{inline(c)}</td>" for c in r) + "</tr>" for r in body]
            out.append("\n".join(table + ["    </tbody>", "  </table>"]))
            continue
        elif not line.strip():
            flush()
        else:
            para.append(line)
        i += 1
    flush()
    return "\n".join(out)


def main() -> None:
    page = PAGE.read_text()
    start, end = page.index("<!-- POLICY:BEGIN"), page.index(END)
    body = to_html(SOURCE.read_text())
    PAGE.write_text(page[:start] + BEGIN + "\n" + body + "\n  " + page[end:])


if __name__ == "__main__":
    main()
